#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
把 data/news.json 转成 data/news.js —— 页面用 <script> 加载，
好处是双击 index.html (file:// 协议) 也能读到数据，不受 fetch / CORS 限制。
"""
import json
import os

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NEWS = os.path.join(BASE, "data", "news.json")
JS = os.path.join(BASE, "data", "news.js")


def main():
    with open(NEWS, encoding="utf-8") as f:
        d = json.load(f)
    eds = d.get("editions", [])
    payload = {"meta": d.get("meta", {}), "editions": eds}
    text = ("/* auto-generated by scripts/build_data.py — 请勿手改 */\n"
            "window.__BRIEF__ = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n")
    with open(JS, "w", encoding="utf-8") as f:
        f.write(text)
    n = os.path.getsize(JS) / 1024
    print(f"OK {JS}  editions={len(eds)}  size={n:.1f}KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
